-- DTR Model Explorer (Streamlit in Snowflake): which registry versions the app can call, the
-- DTR-Bench leaderboard it shows, and the app itself. Run after the services exist.
USE ROLE ACCOUNTADMIN;
USE SCHEMA DECIDER_BENCH.BENCH;

CREATE TABLE IF NOT EXISTS MODEL_ENDPOINTS (
  LABEL STRING, FAMILY STRING, MODEL_NAME STRING, VERSION_NAME STRING, SERVICE_NAME STRING,
  COMPUTE_POOL STRING, USD_PER_HOUR FLOAT, SORT_ORDER INT, ENABLED BOOLEAN DEFAULT TRUE);

CREATE TABLE IF NOT EXISTS DTR_MODEL_SCORES (
  LABEL STRING, SPLIT STRING, N INT, STRICT_ACCURACY FLOAT, FORCED_ACCURACY FLOAT, COVERAGE FLOAT,
  SELECTIVE_ACCURACY FLOAT, ABSTAIN_RECALL FLOAT, ECE FLOAT, SOURCE STRING, SCORED_AT TIMESTAMP_LTZ);

CREATE STAGE IF NOT EXISTS DTR_EXPLORER_APP;
-- PUT file://streamlit/dtr_model_explorer/* @DTR_EXPLORER_APP AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
CREATE OR REPLACE STREAMLIT DTR_MODEL_EXPLORER
  ROOT_LOCATION = '@DECIDER_BENCH.BENCH.DTR_EXPLORER_APP'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = DECIDER_BENCH_WH
  TITLE = 'DTR Model Explorer';
